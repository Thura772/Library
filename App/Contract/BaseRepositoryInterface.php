<?php

namespace App\Contract;

interface BaseRepositoryInterface
{
    /*
    |--------------------------------------------------------------------------
    | GET BY ID
    |--------------------------------------------------------------------------
    */

    public function getById(
        int $id
    ): mixed;

    /*
    |--------------------------------------------------------------------------
    | GET ALL
    |--------------------------------------------------------------------------
    */

    public function getAll(
        ?int $limit = null,
        int $offset = 0
    ): array;

    /*
    |--------------------------------------------------------------------------
    | COUNT
    |--------------------------------------------------------------------------
    */

    public function count(): int;
}