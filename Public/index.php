<?php

declare(strict_types=1);

ini_set('display_errors', '1');
error_reporting(E_ALL);

/*
|--------------------------------------------------------------------------
| BASE PATHS
|--------------------------------------------------------------------------
*/
define('BASE_PATH', realpath(__DIR__ . '/..'));
define('BASE_URL', '/Library');


/*
|--------------------------------------------------------------------------
| AUTOLOADER
|--------------------------------------------------------------------------
*/
require_once BASE_PATH . '/vendor/autoload.php';

use App\Core\ErrorHandler;
use Dotenv\Dotenv;

/*
|--------------------------------------------------------------------------
| SESSION (MUST START FIRST)
|--------------------------------------------------------------------------
*/

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

/*
|--------------------------------------------------------------------------
| ENV LOAD
|--------------------------------------------------------------------------
*/
$dotenv = Dotenv::createImmutable(BASE_PATH);
$dotenv->load();


require_once BASE_PATH . '/view/ItemView.php';

/*
|--------------------------------------------------------------------------
| ROUTES (LOAD FIRST)
|--------------------------------------------------------------------------
*/
require_once BASE_PATH . '/routes/api.php';
require_once BASE_PATH . '/routes/web.php';

/*
|--------------------------------------------------------------------------
| ERROR HANDLER (REGISTER LAST)
|--------------------------------------------------------------------------
| IMPORTANT: register AFTER everything is loaded
|--------------------------------------------------------------------------
*/
ErrorHandler::register();

/*
|--------------------------------------------------------------------------
| REQUEST DISPATCH
|--------------------------------------------------------------------------
*/
$page = $_GET['page'] ?? 'catalog';

/*
|--------------------------------------------------------------------------
| API ROUTING
|--------------------------------------------------------------------------
*/
if (str_starts_with($page, 'api/')) {
    handleApi($page);
    exit;
}

/*
|--------------------------------------------------------------------------
| WEB ROUTING
|--------------------------------------------------------------------------
*/
handleWeb($page);
